"""Run repeatable batch ImageGen through ChatGPT-authenticated Codex CLI.

No API key. Existing valid, vision-reviewed assets are never regenerated by
default, preserving Plus quota and locally approved image provenance.
"""
from __future__ import annotations

import json
import os
import pathlib
import subprocess
import time
from .io import now, outdir, write_json
from .media import plan_media
from .media_workflow import png_dimensions, normalize_observations

def build_batch_prompt(job: dict, manifest: dict, missing: list[dict],
                       directory: pathlib.Path) -> str:
    lines = [
        "Use the BUILT-IN Codex ImageGen tool to create one distinct actual raster image "
        "for each item, using one ImageGen invocation per asset.",
        "These are 16:9 practical instructional editorial illustrations for safe delivery "
        "inspection, NOT commercial photos of real products. Never show any life-size doll, "
        "human portrait, lingerie, anatomy, branding, readable text, labels or watermarks.",
        "Do not use SVG, Pillow, Python-rendered substitutes or any API key fallback.",
        "Use the installed imagegen skill, and copy actual output from CODEX_HOME if needed.",
        "After generating each asset, inspect its actual pixels with view_image. Reject "
        "mismatched photos; do not invent visual verification.",
        "Do not modify tracked files or publish content. Work only in: " + str(directory),
        "Save a machine visual observation JSON array at: "
        + str(directory / "visual-observations-batch.json"),
        "Each JSON object must include id, filename, tool_generated true, "
        "reviewer codex_image_vision_review, observed_scene, matches_article_section "
        "boolean, visible_objects array, mismatches array, and seo_metadata fields "
        "title, alt, caption, description. Metadata describes actual pixels only; "
        "write distinct text for every photo and distinguish Alt from Caption/Description.",
        "These are AI-generated illustrative scenes, not authenticated customer photos.",
        "GENERATE EACH BELOW AS SEPARATE IMAGE FILE:"
    ]
    for item in missing:
        path = directory / (item["id"] + ".png")
        lines.append(item["id"] + " save=" + str(path) + "\n" + item["prompt"])
    return "\n\n".join(lines)

def run_imagegen(job: dict, article: str, *, model: str = "gpt-6.1-terra",
                 timeout: int = 480) -> dict:
    if model != "gpt-6.1-terra":
        raise ValueError("Only the verified GPT-6.1 Terra Codex ImageGen runner is supported")
    root = outdir(job)
    media_dir = root / "media"
    media_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = root / "media-manifest.json"
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    else:
        manifest = plan_media(job, article)
        write_json(manifest_path, manifest)
    old_path = media_dir / "visual-observations.json"
    prior = normalize_observations(json.loads(old_path.read_text(encoding="utf-8"))) if old_path.is_file() else []
    by_id = {v.get("id"): v for v in prior}
    missing = []
    for asset in manifest["assets"]:
        path = media_dir / (asset["id"] + ".png")
        obs = by_id.get(asset["id"])
        if (path.is_file() and isinstance(obs, dict)
            and obs.get("matches_article_section") is True
            and obs.get("reviewer") == "codex_image_vision_review"
            and obs.get("tool_generated") is True
            and not obs.get("mismatches")):
            try:
                png_dimensions(path)
                continue
            except ValueError:
                pass
        if path.exists():
            # Existing image not yet verified: only inspect it. Never overwrite.
            raise RuntimeError("Unverified existing image requires separate visual review: " + str(path))
        missing.append(asset)
    if not missing:
        return {"status": "CACHE_HIT", "model_calls": 0,
                "images_cached": len(manifest["assets"]), "images_generated": 0,
                "note": "No new subscription quota consumed"}
    prompt = build_batch_prompt(job, manifest, missing, media_dir)
    args = ["codex", "exec", "-C", str(outdir(job).parent.parent),
            "-s", "workspace-write", "-m", model, "--json",
            "-c", 'model_reasoning_effort="low"', "-"]
    # Codex working directory is explicitly the repository root, not a website.
    from .io import ROOT
    args[3] = str(ROOT)
    started = time.monotonic()
    try:
        proc = subprocess.run(args, input=prompt, capture_output=True,
                              text=True, timeout=timeout)
    except subprocess.TimeoutExpired as err:
        raise RuntimeError("Codex image generation exceeded bounded timeout") from err
    events = []
    for line in proc.stdout.splitlines():
        try:
            events.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    done = [e for e in events if e.get("type") == "turn.completed"]
    result = {"timestamp": now(), "job_id": job["job_id"], "model": model,
              "image_count_requested": len(missing), "duration_seconds":
              round(time.monotonic()-started, 2),
              "usage": done[-1].get("usage", {}) if done else None,
              "status": "success" if proc.returncode == 0 and done else "failed",
              "billing_note": "ChatGPT subscription usage; image tool quota not separately itemized"}
    with (root / "imagegen-usage-ledger.jsonl").open("a", encoding="utf-8") as f:
        f.write(json.dumps(result, sort_keys=True)+"\n")
    (media_dir / "imagegen-events.jsonl").write_text(proc.stdout, encoding="utf-8")
    (media_dir / "imagegen-stderr.log").write_text(proc.stderr[-10000:], encoding="utf-8")
    if result["status"] != "success":
        raise RuntimeError("Codex ImageGen session failed; partial images remain unapproved")
    batch_path = media_dir / "visual-observations-batch.json"
    if not batch_path.is_file():
        raise RuntimeError("Generated images have no actual visual observation record")
    new = normalize_observations(json.loads(batch_path.read_text(encoding="utf-8")))
    for entry in new:
        if entry.get("id") in {item["id"] for item in missing}:
            by_id[entry["id"]] = entry
    write_json(old_path, list(by_id.values()))
    for asset in missing:
        path = media_dir / (asset["id"] + ".png")
        if not path.is_file():
            raise RuntimeError("ImageGen did not produce actual image: " + asset["id"])
        png_dimensions(path)
    return {"status": "VISION_REVIEW_PENDING_IMPORT", "model_calls": 1,
            "images_generated": len(missing), "images_cached":
            len(manifest["assets"])-len(missing), "usage": result["usage"]}
